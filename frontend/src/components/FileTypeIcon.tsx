export default function FileTypeIcon({ type, size = 20, className = "" }: FileTypeIconProps) {
  const category = getFileCategory(type);
  const color = getFileCategoryColor(type);

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      className={className}
      aria-label={`${type} file`}
    >
      <IconPath category={category} />
    </svg>
  );
}

/** Helper untuk dipakai di komponen lain sebagai JSX element */
export function getFileTypeIcon(type: string, size = 20) {
  return <FileTypeIcon type={type} size={size} />;
}
